import {BASE} from './lib.mjs';
// When each player was last in the game: marked as they use it, in words in Amigos, Todos los jugadores and the profile
import {chromium} from './pw.mjs';
const API=BASE+'/api/t', out=process.argv[2];
const post=async b=>{ const r=await fetch(API,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(b)}); return r.json(); };
const sql=async(q,params)=>(await fetch(BASE+'/__sql',{method:'POST',body:JSON.stringify({sql:q,params})})).json();
let fails=0; const ok=(c,m)=>{ console.log((c?'PASS ':'FAIL ')+m); if(!c) fails++; };
const reg=n=>post({action:'register',name:n,pin:'1234',color:'#2f6fd6'});
const A=await reg('Jero'), B=await reg('Faca'), C=await reg('Javo');
await post({action:'fadd',player:B.player.id,token:A.token}); await post({action:'faccept',player:A.player.id,token:B.token});
await post({action:'fadd',player:C.player.id,token:A.token}); await post({action:'faccept',player:A.player.id,token:C.token});
await sql(`update users set seen_at=now()-interval '3 days' where id=$1`,[B.player.id]);
await sql(`update users set seen_at=now()-interval '1 hour' where id=$1`,[A.player.id]);
const pl=(await (await fetch(API+'?players=1')).json()).players; ok(pl.every(p=>'seen_at' in p),'la lista de jugadores trae la última conexión');
const b=await chromium.launch(); const errs=[];
const p=await (await b.newContext({viewport:{width:844,height:390}})).newPage(); p.on('pageerror',e=>errs.push(String(e)));
await p.addInitScript(([a])=>{ localStorage.clear(); localStorage.setItem('odb-players',JSON.stringify({list:[{id:a.player.id,name:a.player.name,color:a.player.color,token:a.token,created:0,rec:{},best:{},history:[],tours:[]}],cur:a.player.id})); },[A]);
await p.goto(BASE+'/'); await p.waitForSelector('.m-people'); await p.waitForTimeout(1200);
const mine=(await sql('select seen_at from users where id=$1',[A.player.id])); const ago=(Date.now()-new Date(mine[0]?.seen_at??mine.rows?.[0]?.seen_at))/1000;
ok(ago<30,`abrir el juego marca la conexión (hace ${Math.round(ago)} s)`);
await p.click('.m-people'); await p.waitForSelector('#flist .u-item'); await p.waitForTimeout(400);
const fl=await p.$$eval('#flist button.u-item',l=>l.map(e=>e.textContent)); console.log('   amigos:',fl.join(' | '));
ok(fl.some(t=>/Faca.*Hace 3 días/i.test(t))&&fl.some(t=>/Javo.*En línea/i.test(t)),'Amigos: Faca hace 3 días, Javo en línea');
await p.screenshot({path:out+'/amigos.png'});
await p.click('.btns [data-act="people"]'); await p.waitForSelector('.u-list .u-item'); await p.waitForTimeout(600);
const all=await p.$$eval('.u-list .u-item',l=>l.map(e=>e.textContent)); console.log('   todos:',all.join(' | '));
ok(all.some(t=>/Faca.*Hace 3 días/.test(t))&&!all.some(t=>/Vos.*(Hace|En línea)/.test(t)),'Todos los jugadores: la de los demás (la tuya no)');
await p.screenshot({path:out+'/todos.png'});
await p.click(`[data-act="person"][data-id="${B.player.id}"]`); await p.waitForSelector('.u-big'); await p.waitForTimeout(500);
const prof=await p.textContent('.p-row'); ok(/Última conexión: hace 3 días/.test(prof),'su perfil: última conexión hace 3 días');
await p.screenshot({path:out+'/perfil.png'});
ok(!errs.length,'sin errores'+(errs[0]?': '+errs[0]:'')); await b.close();
